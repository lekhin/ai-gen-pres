# -*- coding: utf-8 -*-
"""Смоук-тест модулей книжной вёрстки: pptx_metrics + pptx_book.
Собирает полосатый тестовый pptx, прогоняет его через qa. Запуск из корня
фабрики:  python _service\\skills\\universal-pptx\\scripts\\smoke_book.py [out.pptx]
"""
import os
import sys
import tempfile
from pathlib import Path

os.environ.setdefault("DECK_THEME", "book")
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from deck_theme import template_path                       # noqa: E402
from pptx_helpers import load_template, layouts            # noqa: E402
from pptx_book import (Band, lead, list_h, note, page, plate, picto, pyramid,  # noqa: E402
                       sect, spread_cols, steps_ribbon, box, num)

out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(tempfile.gettempdir()) / "smoke_book.pptx"
band = Band()
prs = load_template(template_path())
L_COVER, L_CONTENT, L_IMAGE = layouts(prs)

# 1 · чек-листы в две колонки (с заголовками групп и без них)
s = page(prs, L_CONTENT, band, "Смоук · чек-листы в две колонки", "Смоук 1")
lead(s, band, band.mx, band.top - 0.55, band.w, "Вводная строка полосы — курсивом.")
spread_cols(s, band, [
    ("Клиническая часть", [box("сформулирована задача КТ"),
                           box("просмотрены доступные предыдущие исследования"),
                           box("исключено ненужное дублирование")]),
    ("Радиационная часть", [box("пациент понимает, что КТ использует излучение"),
                            box("не используется выражение «абсолютно безопасно»"),
                            box("CTDIvol и DLP не выдаются за индивидуальный риск")]),
    ("Коммуникация", [box("объяснена польза"), box("понимание проверено")]),
])

# 2 · нумерованный список без заголовков групп + плашка и выноска
s = page(prs, L_CONTENT, band, "Смоук · нумерованный список", "Смоук 2")
spread_cols(s, band, [(None, [num(i, t) for i, t in enumerate(
    ["Какой клинический вопрос должен решить метод визуализации?",
     "Почему выбран именно этот метод?", "Использует ли он ионизирующее излучение?",
     "Каков основной релевантный риск?", "Применяется ли контрастное средство?",
     "Существует ли диагностически равноценная альтернатива?",
     "Каковы последствия отказа или задержки?", "Есть ли особые обстоятельства?",
     "Нужна ли пациенту численная оценка риска?", "Что необходимо документировать?"],
    1)])], end_y=band.end - 3.0)
y = sect(s, band, band.mx, band.end - 2.4, band.w, "Плашка с правилом")
y = plate(s, band.mx, y, band.w,
          "Зачем → что будем делать → основные риски → что делаем для их уменьшения "
          "→ альтернативы → последствия отказа → вопросы → понимание → решение",
          italic=True)
note(s, band, band.mx, y + 0.2, band.w, "Выноска у поля — курсивный набор.")

# 3 · лента шагов
s = page(prs, L_CONTENT, band, "Смоук · вертикальная лента шагов", "Смоук 3")
lead(s, band, band.mx, band.top - 0.55, band.w, "Девять шагов, читаемых сверху вниз.")
steps_ribbon(s, band, [("Зачем?", "«Исследование нужно, чтобы…»"),                       ("Что даст результат?", "«Если мы увидим…, это изменит…»"),
                       ("Какой главный риск?", "Только релевантный: ИИИ · контраст · "
                                               "процедура · внутренний РФЛП"),
                       ("Что делаем для уменьшения?", "Оптимизация протокола, контроль."),
                       ("Есть ли альтернатива?", "Метод с равноценным ответом."),
                       ("Что будет, если не делать?", "Риск отказа и задержки."),
                       ("Вопрос пациента", "«Что вас больше всего беспокоит?»"),
                       ("Проверка понимания", "«Расскажите своими словами…»"),
                       ("Решение", "Согласие · отказ · второе мнение.")],
           y_top=band.top + 0.9,
           head=("ШАГ", "ЧТО ЗВУЧИТ В БЕСЕДЕ"),
           pictos=[picto(k) for k in ("question", "chevron", "warning", "down", "fork",
                                      "prohibition", "bubble_q", "dialog", "decision")])

# 4 · пирамида уровней
s = page(prs, L_CONTENT, band, "Смоук · пирамида уровней", "Смоук 4")
from pptx_book import ACCENT, FSOFT, SOFT, TINT                          # noqa: E402
pyramid(s, band, [
    ("Уровень 1", "Нормативные требования", "Обязательные российские требования",
     ["ФЗ-323 · ФЗ-3 · СанПиН 2.6.4115-25"], "Определяют права и обязанности.", ACCENT),
    ("Уровень 2", "Методические документы", "Российские методические документы",
     ["МР 2.6.1.0429-26 · МР 2.6.1.0296-22"], "Не всякое МР — норма закона.", TINT),
    ("Уровень 3", "Международные стандарты", "Международные рекомендации",
     ["IAEA GSR Part 3 · ICRP 105 · ACR"], "Нормой РФ автоматически не становятся.",
     SOFT),
    ("Уровень 4", "Обзоры и исследования", "Систематические обзоры",
     ["эффективность коммуникации · восприятие риска"], None, FSOFT),
])
print("list_h(3 пункта, 8 см, 10 pt):", round(list_h([box("текст пункта чек-листа")] * 3,
                                                     8.0), 2), "см")
prs.save(out)
print("saved:", out)
